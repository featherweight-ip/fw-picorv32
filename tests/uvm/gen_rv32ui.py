#!/usr/bin/env python3
"""Write tests/uvm/rv32ui.yaml: one wb-eq-rv32ui-<name> and rtl-eq-rv32ui-<name>
SimRun root per tests/sw/rv32ui-<name>.hex (built by tests/sw/rv32ui/build.py),
plus wb-eq-rv32ui / rtl-eq-rv32ui aggregates. Re-run after adding tests."""
import glob
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SW = os.path.join(HERE, "..", "sw")


def main():
    names = sorted(os.path.basename(p)[len("rv32ui-"):-len(".hex")]
                   for p in glob.glob(os.path.join(SW, "rv32ui-*.hex")))
    out = [
        "# yaml-language-server: $schema=https://dv-flow.github.io/flow.dv.schema.json",
        "#",
        "# Generated by tests/uvm/gen_rv32ui.py -- do not edit.",
        "# rv32ui riscv-tests side by side (images from tests/uvm/flow.yaml); the",
        "# bench also FAILs if the test writes TOHOST != 1 (tb/wb_mem.sv).",
        "#   dfm run wb-eq-rv32ui-<name> / rtl-eq-rv32ui-<name>   one test",
        "#   dfm run wb-eq-rv32ui / rtl-eq-rv32ui                 all %d" % len(names),
        "fragment:",
        "  tasks:",
    ]
    for view in ("wb", "rtl"):
        for n in names:
            out += [
                "  - root: %s-eq-rv32ui-%s" % (view, n),
                "    uses: hdlsim.vlt.SimRun",
                "    needs: [%s-eq-img]" % view,
                "    with:",
                '      plusargs: ["hex=${{ rootdir }}/tests/sw/rv32ui-%s.hex", "max_cycles=200000"]' % n,
                "",
            ]
        out += [
            "  - root: %s-eq-rv32ui" % view,
            "    passthrough: all",
            "    consumes: none",
            "    needs:",
        ] + ["    - %s-eq-rv32ui-%s" % (view, n) for n in names] + [""]
    with open(os.path.join(HERE, "rv32ui.yaml"), "w") as f:
        f.write("\n".join(out).rstrip() + "\n")


if __name__ == "__main__":
    main()
