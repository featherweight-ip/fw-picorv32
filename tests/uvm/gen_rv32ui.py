#!/usr/bin/env python3
"""Write tests/uvm/rv32ui.yaml: one <bench>-rv32ui-<name> case (SimRun + SimCheck) per
tests/sw/rv32ui-<name>.hex (built by tests/sw/rv32ui/build.py) for each bench
(wb-eq, rtl-eq, tlm-eq, tlm), plus a <bench>-rv32ui aggregate. Re-run after
adding tests."""
import glob
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SW = os.path.join(HERE, "..", "sw")
BENCHES = ("wb-eq", "rtl-eq", "tlm-eq", "tlm")   # each has a <bench>-img


def main():
    names = sorted(os.path.basename(p)[len("rv32ui-"):-len(".hex")]
                   for p in glob.glob(os.path.join(SW, "rv32ui-*.hex")))
    out = [
        "# yaml-language-server: $schema=https://dv-flow.github.io/flow.dv.schema.json",
        "#",
        "# Generated by tests/uvm/gen_rv32ui.py -- do not edit.",
        "# rv32ui riscv-tests (images from tests/uvm/flow.yaml): side by side on",
        "# wb-eq, rtl-eq and tlm-eq, and the tlm model alone on tlm. Every bench",
        "# also FAILs if the test writes TOHOST != 1.",
        "#   dfm run <bench>-rv32ui-<name>   one test (bench: wb-eq rtl-eq tlm-eq tlm)",
        "#   dfm run <bench>-rv32ui          all %d" % len(names),
        "fragment:",
        "  tasks:",
    ]
    for bench in BENCHES:
        for n in names:
            out += [
                "  - name: %s-rv32ui-%s-run" % (bench, n),
                "    uses: hdlsim.vlt.SimRun",
                "    needs: [%s-img, \"flags-run-${{ build }}\"]" % bench,
                "    with:",
                "      mode: test",
                '      plusargs: ["hex=${{ rootdir }}/tests/sw/rv32ui-%s.hex", "max_cycles=200000"]' % n,
                "  - name: %s-rv32ui-%s" % (bench, n),
                "    uses: hdlsim.SimCheck",
                "    needs: [%s-rv32ui-%s-run]" % (bench, n),
                "    with: {name: %s-rv32ui-%s}" % (bench, n),
                "",
            ]
        out += [
            "  - name: %s-rv32ui" % bench,
            "    passthrough: all",
            "    consumes: none",
            "    needs:",
        ] + ["    - %s-rv32ui-%s" % (bench, n) for n in names] + [""]
    with open(os.path.join(HERE, "rv32ui.yaml"), "w") as f:
        f.write("\n".join(out).rstrip() + "\n")


if __name__ == "__main__":
    main()
